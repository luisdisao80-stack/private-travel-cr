-- Despacho diario: tablas providers (choferes / proveedores) y dispatch
-- (asignacion de cada tramo a un proveedor, con neto y nota).
--
-- Pegar COMPLETO en el editor SQL de Supabase (Dashboard -> SQL Editor).
-- Los caracteres con tilde van como escapes Unicode U&'\00e1' para que el
-- editor no los convierta en mojibake (regla del proyecto).
-- Se puede correr mas de una vez: todo es IF NOT EXISTS / ON CONFLICT.
-- =====================================================================

-- ---------- 1. providers ----------
create table if not exists public.providers (
  id            bigint generated by default as identity primary key,
  nombre        text not null unique,
  chat_whatsapp text,                 -- nombre tal cual aparece el chat en WhatsApp
  telefono      text,
  es_planta     boolean not null default false,  -- de planta = sin neto por servicio
  vehiculo      text,                 -- vehiculo habitual
  activo        boolean not null default true,
  notas         text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- ---------- 2. dispatch ----------
-- Un tramo se identifica por reserva + fecha + posicion (1, 2, ...) entre los
-- tramos de esa reserva en esa fecha (mismo criterio que --tramo del script).
create table if not exists public.dispatch (
  id            bigint generated by default as identity primary key,
  order_number  text not null,
  fecha         date not null,
  tramo         smallint not null default 1,
  provider_id   bigint references public.providers(id) on delete set null,
  neto_usd      numeric(10,2),        -- null para choferes de planta
  nota          text,
  estado        text not null default 'asignado'
                check (estado in ('asignado', 'hoja_enviada')),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (order_number, fecha, tramo)
);

create index if not exists dispatch_fecha_idx on public.dispatch (fecha);

-- updated_at automatico
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists providers_set_updated_at on public.providers;
create trigger providers_set_updated_at
  before update on public.providers
  for each row execute function public.set_updated_at();

drop trigger if exists dispatch_set_updated_at on public.dispatch;
create trigger dispatch_set_updated_at
  before update on public.dispatch
  for each row execute function public.set_updated_at();

-- ---------- 3. RLS ----------
-- El admin usa la service role (se salta RLS). Con RLS activado y SIN
-- politicas para anon/authenticated, nadie mas puede leer ni escribir:
-- estas tablas tienen telefonos de choferes y netos, no son publicas.
alter table public.providers enable row level security;
alter table public.dispatch  enable row level security;

