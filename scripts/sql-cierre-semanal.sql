-- =====================================================================
-- Cierre semanal por proveedor (lunes a domingo).
--
-- Dos tablas:
--   cierres       una fila por semana cerrada, con el total congelado.
--   cierre_pagos  una fila por proveedor en esa semana, con sus viajes,
--                 su monto y si ya se le pago.
--
-- Una semana se identifica por su LUNES (date). El cierre congela los
-- montos: despues de cerrar, cambiar un neto en `dispatch` ya no mueve
-- lo que quedo guardado aqui, que es justo lo que se quiere para no
-- recontar ni descuadrar un pago que ya se hizo.
--
-- Pegar COMPLETO en el editor SQL de Supabase (Dashboard -> SQL Editor).
-- Sin tildes en los literales, por la regla del proyecto.
-- Se puede correr mas de una vez: todo es IF NOT EXISTS.
-- Requiere scripts/sql-despacho-providers.sql corrido antes.
-- =====================================================================

-- ---------- 1. cierres ----------
create table if not exists public.cierres (
  semana_lunes  date primary key,
  cerrado_at    timestamptz not null default now(),
  total_usd     numeric(10,2) not null default 0,
  total_viajes  integer not null default 0,
  nota          text
);

-- ---------- 2. cierre_pagos ----------
create table if not exists public.cierre_pagos (
  id                  bigint generated by default as identity primary key,
  semana_lunes        date not null references public.cierres(semana_lunes) on delete cascade,
  provider_id         bigint references public.providers(id) on delete set null,
  proveedor           text not null,           -- nombre congelado al cerrar
  es_planta           boolean not null default false,
  viajes              integer not null default 0,
  monto_usd           numeric(10,2) not null default 0,
  viajes_con_factura  integer not null default 0,  -- entraron por la web
  viajes_sin_factura  integer not null default 0,  -- entraron por WeTravel
  pagado              boolean not null default false,
  pagado_at           timestamptz,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  unique (semana_lunes, provider_id)
);

create index if not exists cierre_pagos_semana_idx   on public.cierre_pagos (semana_lunes);
create index if not exists cierre_pagos_provider_idx on public.cierre_pagos (provider_id);

-- updated_at automatico (la funcion ya la crea el SQL de despacho; se
-- vuelve a declarar aqui para que este archivo corra solo si hace falta)
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists cierre_pagos_set_updated_at on public.cierre_pagos;
create trigger cierre_pagos_set_updated_at
  before update on public.cierre_pagos
  for each row execute function public.set_updated_at();

-- ---------- 3. RLS ----------
-- Igual que providers y dispatch: solo la service role del admin entra.
-- Aqui hay montos de pago a proveedores, no es informacion publica.
alter table public.cierres      enable row level security;
alter table public.cierre_pagos enable row level security;

-- ---------- 4. Acumulado por proveedor y por mes ----------
-- Lo que se le pago a cada proveedor cada mes, sumando las semanas
-- cerradas. Una semana que cruza el cambio de mes cuenta entera en el
-- mes de su lunes, que es como se cierra y como se paga.
create or replace view public.cierre_mensual as
select
  to_char(date_trunc('month', semana_lunes), 'YYYY-MM') as mes,
  provider_id,
  proveedor,
  sum(viajes)::integer             as viajes,
  sum(monto_usd)::numeric(10,2)    as monto_usd,
  sum(viajes_con_factura)::integer as viajes_con_factura,
  sum(viajes_sin_factura)::integer as viajes_sin_factura,
  count(*) filter (where pagado)::integer     as semanas_pagadas,
  count(*) filter (where not pagado)::integer as semanas_pendientes
from public.cierre_pagos
group by 1, 2, 3;

-- Comprobacion rapida
select semana_lunes, total_viajes, total_usd, cerrado_at
from public.cierres order by semana_lunes desc limit 10;
